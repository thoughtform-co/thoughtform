def save(m):
    mime, b64 = m.group(1), m.group(2)
    counter["n"] += 1
    name = "loop.mp4" if mime == "video/mp4" else f"ptl-{counter['n']:02d}.{EXT[mime]}"
    with open(os.path.join(PUB_DIR, name), "wb") as f:
        f.write(base64.b64decode(b64))
    return f"{PUB_URL}/{name}"


