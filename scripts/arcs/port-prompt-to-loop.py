DROP = re.compile(r"^(:root|html|body|\*$|\.bar|\.nav|\.wrap|\.sec|\.head|\.kick|\.title|\.sub$|\.hero(\s|$|,))")


def split_top(sel):
    out, depth, buf = [], 0, ""
    for ch in sel:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(buf.strip()); buf = ""
        else:
            buf += ch
    out.append(buf.strip())
    return [x for x in out if x]


def scope(sel):
    keep = []
    for one in split_top(sel):
        if DROP.match(one):
            continue
        if one == "*":
            keep.append(".ptl *"); continue
        one = re.sub(r"\.(?!ptl-)([A-Za-z][\w-]*)", lambda m: f".ptl-{m.group(1)}", one)
        keep.append(f".ptl {one}")
    return ", ".join(keep)


def walk(block):
    out, i = [], 0
    while i < len(block):
        j = block.find("{", i)
        if j < 0:
            break
        head = block[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(block[k], 0); k += 1
        inner = block[j + 1: k - 1]
        i = k
        if head.startswith("@media") or head.startswith("@supports"):
            if "prefers-color-scheme" in head:
                continue
            sub = walk(inner)
            if sub.strip():
                out.append(f"{head} {{\n{sub}}}\n")
        elif head.startswith("@"):
            out.append(f"{head} {{{inner}}}\n")
        else:
            sel = scope(head)
            if sel:
                out.append(f"{sel} {{{inner.strip()}}}\n")
    return "".join(out)


