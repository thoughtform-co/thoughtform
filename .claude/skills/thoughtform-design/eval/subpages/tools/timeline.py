r"""The fleet's timeline, generated from what came home.

    python tools/timeline.py                 write harvest/TIMELINE.md at the port
    python tools/timeline.py --check         exit 1 when the file is stale
    python tools/timeline.py --port DIR --out FILE

One row per event, newest first: every harvest note that arrived, what was
promoted from it (its line-2 `Promoted:` mark), every breakthrough and verdict
a ship reported in its note's `## Breakthroughs` section, and every release
and read in the port's own `CHANGELOG.md`. The row carries the callsign and
never the client, because the notes it reads were scrubbed before they left
the ship.

The file is generated and never hand-edited: it says so on its first line,
and `--check` fails when it does not match what the notes say. It is
regenerated by a person at read time, as the last step of `/harvest-read`,
and never inside the nightly per-ship branches, where two ships would
conflict over one file.

Everything here is the standard library. The notes carry non-ASCII in their
promoted lines, so every write is UTF-8 and the console output is kept ASCII.
"""
from __future__ import annotations

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import config  # noqa: E402

_NOTE = re.compile(r"^(?P<date>\d{4}-\d{2}-\d{2})-(?P<callsign>[a-z][a-z0-9-]*?)(?:-(?P<n>\d+))?\.md$")
_DATE = re.compile(r"(\d{4}-\d{2}-\d{2})")
_RELEASE = re.compile(r"^## (?P<version>\d+\.\d+\.\d+)\b(?P<rest>.*)$")
_READ = re.compile(r"^## Read\b(?P<rest>.*)$")
_HEADER = re.compile(r"^Harness (?P<rest>.*)$")

KINDS = ("breakthrough", "verdict", "promoted", "harvest", "release", "read")
MAX_LINE = 140


def _read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def _cut(text: str, n: int = MAX_LINE) -> str:
    text = " ".join(text.split())
    return text if len(text) <= n else text[: n - 3].rstrip() + "..."


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _section(txt: str, heading: str) -> str:
    m = re.search(r"^## " + re.escape(heading) + r"[^\n]*\n(.*?)(?=^## |\Z)", txt, re.S | re.M)
    return m.group(1) if m else ""


def note_rows(harvest_dir: str) -> list[dict]:
    rows = []
    if not os.path.isdir(harvest_dir):
        return rows
    for name in sorted(os.listdir(harvest_dir)):
        m = _NOTE.match(name)
        if not m:
            continue
        path = os.path.join(harvest_dir, name)
        try:
            txt = _read(path)
        except OSError:
            continue
        date, callsign = m.group("date"), m.group("callsign")
        lines = txt.splitlines()
        header = ""
        for line in lines[1:6]:
            h = _HEADER.match(line.strip())
            if h:
                header = "harness " + h.group("rest").strip()
                break
        rows.append({"date": date, "callsign": callsign, "kind": "harvest",
                     "line": _cut(header or "a note came home"), "source": name})
        if len(lines) > 1 and lines[1].startswith("Promoted:"):
            body = lines[1][len("Promoted:"):].strip()
            d = _DATE.search(body)
            rows.append({"date": d.group(1) if d else date, "callsign": callsign,
                         "kind": "promoted", "line": _cut(body), "source": name})
        for e in _breakthroughs(_section(txt, "Breakthroughs")):
            rows.append({"date": e["date"] or date, "callsign": callsign,
                         "kind": e["tag"] or "breakthrough",
                         "line": _cut(e["text"] + (("  -> " + e["pointer"]) if e["pointer"] else "")),
                         "source": name})
    return rows


def _breakthroughs(body: str) -> list[dict]:
    """The bullets of a note's `## Breakthroughs` section, in the memory grammar."""
    out = []
    for raw in body.splitlines():
        line = raw.rstrip()
        if not line.startswith("- "):
            continue
        m = config._MEMORY_LINE.match(line)
        if not m:
            continue
        out.append({"date": m.group("date"), "tag": m.group("tag") or "",
                    "text": m.group("text").strip(), "pointer": (m.group("pointer") or "").strip()})
    return out


def changelog_rows(changelog: str) -> list[dict]:
    rows = []
    if not os.path.isfile(changelog):
        return rows
    for line in _read(changelog).splitlines():
        r = _RELEASE.match(line)
        if r:
            d = _DATE.search(r.group("rest"))
            rows.append({"date": d.group(1) if d else "", "callsign": "port", "kind": "release",
                         "line": _cut(r.group("version") + " " + r.group("rest").strip(" ,-—")),
                         "source": os.path.basename(changelog)})
            continue
        r = _READ.match(line)
        if r:
            d = _DATE.search(r.group("rest"))
            rows.append({"date": d.group(1) if d else "", "callsign": "port", "kind": "read",
                         "line": _cut(r.group("rest").strip(" ,-—")),
                         "source": os.path.basename(changelog)})
    return [r for r in rows if r["date"]]


def build(port: str) -> str:
    harvest_dir = os.path.join(port, "harvest")
    rows = note_rows(harvest_dir) + changelog_rows(os.path.join(port, "CHANGELOG.md"))
    order = {k: i for i, k in enumerate(KINDS)}
    rows.sort(key=lambda r: (r["date"], r["callsign"], -order.get(r["kind"], 99)), reverse=True)
    notes = sum(1 for r in rows if r["kind"] == "harvest")
    marks = sum(1 for r in rows if r["kind"] in ("breakthrough", "verdict"))
    ships = sorted({r["callsign"] for r in rows if r["callsign"] != "port"})
    out = []
    out.append("# Timeline")
    out.append("")
    out.append("Generated by `tools/timeline.py` from `harvest/*.md` and `CHANGELOG.md`. "
               "Never hand-edited; regenerate after a note is read.")
    out.append("")
    out.append(str(len(rows)) + " events, " + str(notes) + " notes, " + str(marks)
               + " breakthroughs and verdicts, " + str(len(ships)) + " ships ("
               + ", ".join(ships) + "). Newest first. Ships by callsign, never by client.")
    out.append("")
    out.append("| Date | Callsign | Kind | What | Source |")
    out.append("|---|---|---|---|---|")
    for r in rows:
        out.append("| " + r["date"] + " | " + r["callsign"] + " | " + r["kind"] + " | "
                   + _cell(r["line"]) + " | `" + r["source"] + "` |")
    out.append("")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description="Write the fleet's timeline from the harvest notes.")
    ap.add_argument("--port", default=None, metavar="DIR",
                    help="the home port (default: the repo this tool lives in)")
    ap.add_argument("--out", default=None, metavar="FILE",
                    help="write here instead of <port>/harvest/TIMELINE.md")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the file on disk differs from what the notes say")
    a = ap.parse_args()

    port = os.path.abspath(os.path.expanduser(a.port or str(config.REPO)))
    out = a.out or os.path.join(port, "harvest", "TIMELINE.md")
    text = build(port)
    rows = text.count("\n| ") - 1

    if a.check:
        try:
            current = _read(out)
        except OSError:
            print("  timeline    " + out + " is missing; run tools/timeline.py")
            raise SystemExit(1)
        if current != text:
            print("  timeline    " + out + " is stale; run tools/timeline.py")
            raise SystemExit(1)
        print("  timeline    current, " + str(rows) + " events")
        raise SystemExit(0)

    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("  timeline    " + out)
    print("  events      " + str(rows))
    raise SystemExit(0)


if __name__ == "__main__":
    main()
